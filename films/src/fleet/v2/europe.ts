const POLYGONS = [MAINLAND, NORDIC, BRITAIN, IRELAND, SICILY, SARDINIA, CORSICA];

function inside([x, y]: [number, number], polygon: Polygon) {
  let hit = false;
  for (let i = 0, j = polygon.length - 1; i < polygon.length; j = i++) {
    const [xi, yi] = polygon[i];
    const [xj, yj] = polygon[j];
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) hit = !hit;
  }
  return hit;
}

/** Map projection on the 1920 × 1080 frame (plain equirectangular, stretched to look right). */
export const project = (lon: number, lat: number) => ({ x: 960 + (lon - 10) * 21, y: 560 - (lat - 53.5) * 26 });

/** Every dot of the map, in frame pixels. */
export const EUROPE_DOTS: { x: number; y: number }[] = (() => {
  const dots: { x: number; y: number }[] = [];
  for (let lat = 35.5; lat <= 71.5; lat += 0.62) {
    for (let lon = -11; lon <= 32; lon += 0.8) {
      if (POLYGONS.some((p) => inside([lon, lat], p))) dots.push(project(lon, lat));
    }
  }
  return dots;
})();

